/** 按 ID 查询勇者配置 */
export function getHeroById(heroId) {
  return HEROES.find((h) => h.id === heroId) || null;
}

/** 按 ID 查询物品配置 */
export function getItemById(itemId) {
  return ITEMS[itemId] || null;
}

/** 按轮次（1..10）查询敌方波次配置 */
export function getEnemyByRound(round) {
  if (!ENEMY_WAVES.length) return null;
  const r = Math.max(1, Math.min(ENEMY_WAVES.length, Math.floor(Number(round) || 1)));
  return ENEMY_WAVES[r - 1] || null;
}

/** 检查两件物品是否匹配跨物品★神话合成配方（顺序无关） */
export function findMythicRecipe(itemIdA, itemIdB) {
  if (!itemIdA || !itemIdB) return null;
  for (const recipe of MYTHIC_RECIPES) {
    const matchForward = recipe.ingredientA.includes(itemIdA) && recipe.ingredientB.includes(itemIdB);
    const matchReverse = recipe.ingredientA.includes(itemIdB) && recipe.ingredientB.includes(itemIdA);
    if (matchForward || matchReverse) {
      return recipe;
    }
  }
  return null;
}

/** 获取指定轮次的商店可刷新物品池（仅包含 shopWeight > 0 且 shopMinRound <= round 的物品） */
export function getShopPoolForRound(round) {
  const r = Math.max(1, Math.floor(Number(round) || 1));
  return Object.values(ITEMS).filter((item) => item.shopWeight > 0 && item.shopMinRound <= r);
}
